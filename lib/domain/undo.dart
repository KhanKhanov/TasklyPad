/// Отмена действия для тоста «Отменить»: интерфейс узнаёт, есть ли что
/// отменять, и запускает отмену. Как она записывается — дело lib/sync
/// (`Undo` в mutator.dart).
abstract interface class UndoAction {
  /// Отменять нечего: действие ничего не изменило.
  bool get isEmpty;

  /// Вернуть прежнее состояние.
  Future<void> call();
}
