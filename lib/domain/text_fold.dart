/// Текст для сравнения без учёта регистра и с «ё» как «е» — одна свёртка для
/// фильтров, поиска, сортировки по имени и разбора дат (допущение О-69:
/// Todoist «ё» и «е» не различает в поиске русского текста).
String foldText(String text) => text.toLowerCase().replaceAll('ё', 'е');

/// Ключ уникальности имени метки: без пробелов по краям, без учёта регистра,
/// «ё» = «е» ([foldText]; решение 9А plans/m6) — так же, как метку находят
/// фильтр и поиск. «Елка» рядом с «Ёлкой» не создаётся; пары, созданные до
/// этого правила или офлайн на двух устройствах, остаются.
String labelNameKey(String name) => foldText(name.trim());
