/// Очередь шагов по одному: каждый шаг начинается после окончания
/// предыдущего, в порядке вызова [run]. Так две быстрые правки одного
/// значения (журнал «Уведомления», недавно просмотренное, недавние запросы,
/// тема) не читают его одновременно и не теряют друг друга.
///
/// Сбой шага очередь не останавливает: его ошибка достаётся только тому, кто
/// вызвал [run] (возвращённый `Future`), а следующий шаг начинается как
/// обычно. Как сообщить об ошибке — решает вызывающий: ловит её внутри шага
/// (лог) или получает из `Future`.
final class SerialQueue {
  Future<void> _tail = Future<void>.value();

  /// Выполнить [step] после всех поставленных раньше; результат или ошибка
  /// шага — в возвращённом `Future`.
  Future<T> run<T>(Future<T> Function() step) {
    final result = _tail.then((_) => step());
    _tail = result.then<void>((_) {}, onError: (Object _) {});
    return result;
  }
}
